using UnityEngine;

namespace RockAndHardPlace
{
    public enum SoundCue { Cannon, StoneHit, KingdomHit, Footstep, MountainWake, Upgrade, Victory }

    [RequireComponent(typeof(AudioSource))]
    public sealed class GameAudio : MonoBehaviour
    {
        [Header("Original effects generated by scripts/generate_sfx.py")]
        [SerializeField] private AudioClip cannon;
        [SerializeField] private AudioClip stoneHit;
        [SerializeField] private AudioClip kingdomHit;
        [SerializeField] private AudioClip footstep;
        [SerializeField] private AudioClip mountainWake;
        [SerializeField] private AudioClip upgrade;
        [SerializeField] private AudioClip victory;
        [SerializeField, Range(0, 1)] private float volume = 0.65f;

        private static GameAudio current;
        private AudioSource source;

        private void Awake()
        {
            current = this;
            source = GetComponent<AudioSource>();
            source.playOnAwake = false;
            source.spatialBlend = 0; // Both local players hear the same clear feedback.
        }

        private void OnDestroy()
        {
            if (current == this) current = null;
        }

        public static void Play(SoundCue cue, float gain = 1)
        {
            if (current == null || !current.isActiveAndEnabled) return;
            AudioClip clip = current.GetClip(cue);
            if (clip != null) current.source.PlayOneShot(clip, current.volume * Mathf.Clamp01(gain));
        }

        private AudioClip GetClip(SoundCue cue)
        {
            switch (cue)
            {
                case SoundCue.Cannon: return cannon;
                case SoundCue.StoneHit: return stoneHit;
                case SoundCue.KingdomHit: return kingdomHit;
                case SoundCue.Footstep: return footstep;
                case SoundCue.MountainWake: return mountainWake;
                case SoundCue.Upgrade: return upgrade;
                case SoundCue.Victory: return victory;
                default: return null;
            }
        }
    }
}
